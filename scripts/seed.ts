// Generates migrations/0001_seed.sql from scripts/seed-data.ts, and the test fixture
// test/fixtures/test-family.sql from scripts/fixtures.ts.
//   npm run seed:generate          write the file
//   npm run seed:generate -- --check   fail if the file is out of date (used by CI via the unit tests too)
//
// IDs are ULIDs from a seeded PRNG, so output is deterministic and re-running produces no diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ulid } from 'ulid';
import { buildTestFamilySql, TEST_FAMILY_PATH } from './fixtures';
import { SEED_AT, seedActivityTypes } from './seed-data';
import { insert, prng } from './sql';

export const SEED_MIGRATION_PATH = fileURLToPath(new URL('../migrations/0001_seed.sql', import.meta.url));

export function buildSeedSql(): string {
  const rand = prng(20261018);
  const time = Date.parse(SEED_AT);
  const id = () => ulid(time, rand);
  const ts = { created_at: SEED_AT, updated_at: SEED_AT };
  const out: string[] = [
    '-- Seed data (requirements section 8). GENERATED by `npm run seed:generate` from scripts/seed-data.ts.',
    '-- Do not edit by hand. Built-in activity types and fields only: no users, children, schedule or medicines.',
  ];

  out.push(insert('sync_state', { id: 1, version: 1 }));

  seedActivityTypes.forEach((t, i) => {
    const tid = id();
    out.push(
      insert('activity_types', {
        id: tid,
        system_key: t.systemKey ?? null,
        name: t.name,
        kind: t.kind,
        icon: t.icon,
        colour: t.colour,
        sort_order: i,
        archived_at: null,
        ...ts,
      }),
    );
    t.fields.forEach((f, j) => {
      out.push(
        insert('activity_fields', {
          id: id(),
          activity_type_id: tid,
          key: f.key,
          label: f.label,
          field_type: f.fieldType,
          unit: f.unit ?? null,
          decimals: f.decimals ?? null,
          min: f.min ?? null,
          max: null,
          max_length: f.maxLength ?? null,
          options: f.options ? JSON.stringify(f.options) : null,
          picker_set: f.pickerSet ?? null,
          show_when: f.showWhen ? JSON.stringify(f.showWhen) : null,
          required: f.required ?? false,
          sort_order: j,
          archived_at: null,
          ...ts,
        }),
      );
    });
  });

  return out.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const outputs = [
    { path: SEED_MIGRATION_PATH, sql: buildSeedSql() },
    { path: TEST_FAMILY_PATH, sql: buildTestFamilySql() },
  ];
  if (process.argv.includes('--check')) {
    const stale = outputs.filter((o) => readFileSync(o.path, 'utf8') !== o.sql);
    if (stale.length) {
      for (const o of stale) console.error(`${o.path} is out of date. Run \`npm run seed:generate\`.`);
      process.exit(1);
    }
    console.log('Seed migration and test fixture are up to date.');
  } else {
    for (const o of outputs) {
      writeFileSync(o.path, o.sql);
      console.log(`Wrote ${o.path}`);
    }
  }
}
