// Generates public/icons/icon.svg and the PNG icons from one definition of the mark.
// Run: npm run icons:generate (set PW_CHROMIUM_PATH to use an installed Chromium).
import { writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

// A timeline of logged moments on the dark theme's navy, with the middle row in the
// dark theme's "now" orange, as on Home's timeline.
const NAVY = '#1E2A47';
const WHITE = '#FFFFFF';
const NOW = '#FF8A50';

function mark() {
  const rows = [
    [30, 28, WHITE],
    [50, 22, NOW],
    [70, 14, WHITE],
  ];
  return [
    `<rect x="32.3" y="30" width="2.4" height="40" rx="1.2" fill="${WHITE}" fill-opacity="0.55"/>`,
    ...rows.map(
      ([y, w, c]) =>
        `<circle cx="33.5" cy="${y}" r="5.8" fill="${c}"/><rect x="44" y="${y - 3.6}" width="${w}" height="7.2" rx="3.6" fill="${c}"/>`,
    ),
  ].join('\n  ');
}

// rounded: the app icon shape. Otherwise a full-bleed square with the mark scaled into
// the maskable safe zone (the centre 80%).
function svg({ rounded = true, scale = 1, size } = {}) {
  const dims = size ? ` width="${size}" height="${size}"` : '';
  const t =
    scale === 1 ? '' : ` transform="translate(${50 - 50 * scale} ${50 - 50 * scale}) scale(${scale})"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"${dims} role="img" aria-label="Track">
  <!-- Generated by scripts/icons.mjs. Source of the PNG icons: a timeline of logged moments. -->
  <rect width="100" height="100"${rounded ? ' rx="22"' : ''} fill="${NAVY}"/>
  <g${t}>
  ${mark()}
  </g>
</svg>
`;
}

const outputs = [
  ['icon-192.png', 192, {}],
  ['icon-512.png', 512, {}],
  ['icon-maskable-512.png', 512, { rounded: false, scale: 0.8 }],
  ['favicon-32.png', 32, {}],
];

writeFileSync('public/icons/icon.svg', svg());
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM_PATH || undefined });
try {
  const page = await browser.newPage();
  for (const [file, size, opts] of outputs) {
    await page.setViewportSize({ width: size, height: size });
    await page.setContent(
      `<style>html,body{margin:0;background:transparent}svg{display:block}</style>${svg({ ...opts, size })}`,
    );
    await page.locator('svg').screenshot({ path: `public/icons/${file}`, omitBackground: true });
    console.log(`public/icons/${file}`);
  }
} finally {
  await browser.close();
}
